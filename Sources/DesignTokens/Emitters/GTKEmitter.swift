/// Emits one ``Theme`` slot as a GTK stylesheet for GTK 3 and GTK 4 (and libadwaita applications).
///
/// GTK themes are CSS, so the file is what a user drops in `~/.config/gtk-4.0/gtk.css` (and `gtk-3.0/gtk.css`), or ships as a theme's
/// `gtk.css`. Two things differ from the web files:
/// - GTK reads neither `var()` nor `color-mix()`; colours are literal, as `@define-color` names and as `#RRGGBB` or `rgba()` values.
/// - GTK cannot draw a CSS `data:` image, a backdrop filter or `image-rendering`, so a surface layer that needs one (a pattern, a blur) is
///   left out of the widget rules; the colour and edges of the surface still apply.
///
/// ### Named colours
/// libadwaita applications read `window_bg_color`, `view_bg_color`, `accent_bg_color` and the rest; plain GTK 3 and 4 applications read
/// `theme_bg_color`, `theme_base_color`, `theme_selected_bg_color` and the rest. Both sets are written, from the palette:
/// `window` = background and ink, `view`, `headerbar` and `card` = surface and ink, `accent` = accent and onAccent, `borders` = rule,
/// `success` / `warning` / `error` = positive / warning / negative.
///
/// ### Widgets
/// A theme with a ``SurfaceSet`` styles `window`, `.card`, `button`, `button.default` (the suggested action), `entry` and `spinbutton`
/// from the recipes, state by state (`:hover`, `:active`, `:focus`, `:disabled`, `.error`). A fixed ``LayoutSpec/controlHeight`` becomes
/// the button's and entry's `min-height`. One file is one appearance: ``Generator`` writes `<id>.gtk.css` for the first appearance and
/// `<id>.gtk-dark.css` for a theme that also has a dark one. Increased contrast is not written.
public enum GTKEmitter {
    /// The `settings.ini` that places the window controls the way the theme's platform does, or `nil` for a theme with no placement.
    ///
    /// GTK reads the title bar's layout from the `gtk-decoration-layout` setting, not from CSS, so the placement travels in its own file:
    /// copy it to `~/.config/gtk-3.0/settings.ini` and `~/.config/gtk-4.0/settings.ini`. libadwaita applications read the GNOME
    /// `button-layout` key instead; `gsettings set org.gnome.desktop.wm.preferences button-layout '<layout>'` sets it, with the same value.
    public static func settings(_ theme: Theme) -> String? {
        guard let controls = theme.windowControls else { return nil }
        // This one cannot throw (its signature is public), so the id and name are written as display text: a bad id cannot
        // start a line here, and the stylesheet from `emit` refuses it anyway.
        return "# Generated by design-tokens. Do not edit. Theme: \(ThemeIdentity.displayText(theme.id)) (\(ThemeIdentity.displayText(theme.name))) | DesignTokens \(DesignTokens.version)\n"
            + "[Settings]\ngtk-decoration-layout=\(controls.gtkDecorationLayout)\n"
    }

    /// The stylesheet for one slot of a theme, ending in a newline.
    ///
    /// - Throws: An encoding error if the theme cannot be encoded for its content hash.
    public static func emit(_ theme: Theme, slot: ThemeSlot) throws -> String {
        try ThemeIdentity.requireValidID(of: theme)
        let hash = try ThemeCodec.fingerprint(of: theme)
        var lines = [
            "/* Generated by design-tokens. Do not edit. Theme: \(theme.id) (\(ThemeIdentity.cssCommentText(theme.name))), slot \(slot.name) | DesignTokens \(DesignTokens.version) | hash fnv1a64:\(hash) */",
            "/* GTK 3 and 4 stylesheet. Colours are literal, because GTK reads neither custom properties nor colour mixing. Pattern images and blurs are left out. */",
            "",
        ]

        func hex(_ role: ColorRole) -> String { ColorValue(slot.rgb(theme.palette[role], in: theme)).hex }
        let named: [(String, ColorRole)] = [
            ("window_bg_color", .background), ("window_fg_color", .ink),
            ("view_bg_color", .surface), ("view_fg_color", .ink),
            ("headerbar_bg_color", .surface), ("headerbar_fg_color", .ink),
            ("card_bg_color", .surface), ("card_fg_color", .ink),
            ("accent_bg_color", .accent), ("accent_fg_color", .onAccent), ("accent_color", .link),
            ("destructive_bg_color", .negative), ("destructive_fg_color", .onAccent),
            ("success_color", .positive), ("warning_color", .warning), ("error_color", .negative),
            ("borders", .rule),
            ("theme_bg_color", .background), ("theme_fg_color", .ink),
            ("theme_base_color", .surface), ("theme_text_color", .ink),
            ("theme_selected_bg_color", .accent), ("theme_selected_fg_color", .onAccent),
        ]
        for (name, role) in named { lines.append("@define-color \(name) \(hex(role));") }

        let body = theme.structure.type.body
        lines += [
            "",
            "* {",
            "  font-family: \(ThemeCSSEmitter.family(body.family));",
            "  font-size: \(SurfaceCSS.px(body.size));",
            "}",
            "",
            "window, .background {",
            "  background-color: @window_bg_color;",
            "  color: @window_fg_color;",
            "}",
            "",
            "selection, *:selected {",
            "  background-color: @theme_selected_bg_color;",
            "  color: @theme_selected_fg_color;",
            "}",
            "",
            "headerbar, .titlebar {",
            "  background-color: @headerbar_bg_color;",
            "  background-image: none;",
            "  color: @headerbar_fg_color;",
            "  box-shadow: inset 0 -1px 0 0 @borders;",
            "}",
        ]
        if let mono = theme.structure.monospace {
            lines += [
                "",
                ".monospace {",
                "  font-family: \(ThemeCSSEmitter.family(mono.family));",
                "  font-size: \(SurfaceCSS.px(mono.size));",
                "}",
            ]
        }
        lines += surfaceRules(theme, slot: slot)
        return lines.joined(separator: "\n") + "\n"
    }

    // MARK: Widgets

    private static func selectors(for role: SurfaceRole) -> [String] {
        switch role {
        case .window: ["window"]
        case .panel: [".card"]
        case .button: ["button"]
        case .buttonDefault: ["button.suggested-action", "button.default"]
        case .field: ["entry", "spinbutton"]
        case .desktop, .menu, .menuBar, .menuTitle, .menuItem, .menuBarItem, .menuSeparator, .menuArrow, .dockTile, .dockLabel, .scrollBar, .scrollTrack, .scrollThumb, .scrollGrip, .scrollArrowStart, .scrollArrowEnd, .selection, .titleBar, .titleStripes, .windowBox, .windowBoxZoom, .windowBoxMinimize: []
        }
    }

    private static let states: [(ComponentState, String)] = [
        (.rest, ""), (.hover, ":hover"), (.active, ":active"), (.focus, ":focus"), (.disabled, ":disabled"), (.invalid, ".error"),
    ]

    /// The declarations GTK cannot use: images drawn from `data:` URLs, their size, backdrop filters and image-rendering.
    private static func readable(_ declaration: String) -> Bool {
        if declaration.hasPrefix("background-image:"), declaration.contains("url(") { return false }
        for unreadable in ["background-size:", "image-rendering:", "backdrop-filter:", "-webkit-backdrop-filter:"] where declaration.hasPrefix(unreadable) {
            return false
        }
        return true
    }

    /// A `box-shadow` list written for GTK: GTK paints the first shadow underneath, the opposite of CSS, so the list is reversed and the
    /// deepest stripe comes first. Any other declaration is returned as it is. Commas inside `rgba(...)` do not separate shadows.
    static func stackedForGTK(_ declaration: String) -> String {
        let prefix = "box-shadow: "
        guard declaration.hasPrefix(prefix) else { return declaration }
        var shadows: [String] = []
        var current = ""
        var depth = 0
        for character in declaration.dropFirst(prefix.count) {
            if character == "(" { depth += 1 }
            if character == ")" { depth -= 1 }
            if character == ",", depth == 0 {
                shadows.append(current.trimmedSpaces())
                current = ""
            } else {
                current.append(character)
            }
        }
        shadows.append(current.trimmedSpaces())
        return prefix + shadows.reversed().joined(separator: ", ")
    }

    private static func surfaceRules(_ theme: Theme, slot: ThemeSlot) -> [String] {
        guard let surfaces = theme.surfaces else { return [] }
        func colour(_ reference: ColourReference) -> String {
            let adaptive = ColorRole(rawValue: reference.source).map { theme.palette[$0] } ?? theme.palette.extras[reference.source]
            guard let adaptive else { return "transparent" }
            let rgb = slot.rgb(adaptive, in: theme)
            guard reference.opacity < 1 else { return ColorValue(rgb).hex }
            return "rgba(\(rgb.red), \(rgb.green), \(rgb.blue), \(CSSNumber.string(reference.opacity)))"
        }
        var lines: [String] = []
        for role in SurfaceRole.allCases {
            let nodes = selectors(for: role)
            guard !nodes.isEmpty, let recipes = surfaces.recipes[role] else { continue }
            for (state, suffix) in states {
                guard let recipe = recipes[state] else { continue }
                lines.append("")
                lines.append(nodes.map { $0 + suffix }.joined(separator: ", ") + " {")
                if state == .rest, role == .button || role == .field {
                    // GTK's own button and entry carry a gradient and a border; the recipe owns both.
                    lines += ["  background-image: none;", "  border: none;", "  outline: none;", "  text-shadow: none;",
                              "  -gtk-icon-shadow: none;"]
                    if let controlHeight = theme.structure.layout.controlHeight {
                        lines.append("  min-height: \(SurfaceCSS.px(controlHeight));")
                        lines.append("  padding: 0 \(role == .button ? "16px" : "6px");")
                    }
                }
                if role == .buttonDefault, state == .rest, surfaces.defaultRingExtra > 0, let controlHeight = theme.structure.layout.controlHeight {
                    // the ring is outside the measured button, so the box grows by it on each side
                    lines.append("  min-height: \(SurfaceCSS.px(controlHeight + surfaces.defaultRingExtra * 2));")
                    lines.append("  padding: 0 \(SurfaceCSS.px(16 + surfaces.defaultRingExtra));")
                }
                for declaration in SurfaceCSS.declarations(for: recipe, resolve: colour, literal: colour) where readable(declaration) {
                    lines.append("  \(stackedForGTK(declaration));")
                }
                lines.append("}")
            }
        }
        return lines
    }
}
