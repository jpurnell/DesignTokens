/// The skins gallery: one static page that shows every theme, generated from ``Theme/all`` so it cannot drift from them.
///
/// This is the first slice: the page's shell. It links every theme's stylesheet and `components.css`, lets you switch theme (the choice
/// is kept in the URL hash, so a link names a view), and shows one components scene under the selected theme. The role-by-state
/// matrix, the forced states, the composed skin scenes, backdrops, scale and appearance controls are later slices; see
/// `project/plans/proposals/2026-11-25_SkinsGallery.md`.
///
/// The page's own chrome is neutral (`gallery.css` never names a theme); the only themed element is the stage, which carries
/// `data-theme-name`, so the page exercises the same scoping contract a consumer uses. All links are relative and the script is plain
/// ES2020 with no modules, so the page opens from `file://` and from any static path. It loads nothing from the network.
///
/// ```swift
/// let files = try GalleryEmitter.emit()   // gallery/index.html, gallery/gallery.css, gallery/gallery.js
/// ```
public enum GalleryEmitter {
    /// The gallery's three files, as paths relative to the output directory.
    ///
    /// The switcher lists the themes that define surfaces (the skins) first, then the rest in the order given.
    ///
    /// - Parameter themes: The themes to show; their stylesheets are linked as `../themes/<id>.css`, so they must be written beside it.
    /// - Throws: ``ThemeEmitError/invalidID(_:)`` for a theme whose id is not a slug.
    public static func emit(themes: [Theme] = Theme.all) throws -> [GeneratedFile] {
        for theme in themes { try ThemeIdentity.requireValidID(of: theme) }
        let ordered = themes.filter { $0.surfaces != nil } + themes.filter { $0.surfaces == nil }
        return [
            GeneratedFile(path: "gallery/index.html", contents: try page(ordered)),
            GeneratedFile(path: "gallery/gallery.css", contents: stylesheet),
            GeneratedFile(path: "gallery/gallery.js", contents: script),
        ]
    }

    // MARK: The page

    private static func page(_ themes: [Theme]) throws -> String {
        let first = themes.first?.id ?? ""
        let skinScenes = try themes.compactMap { theme -> String? in
            guard let scene = try GalleryScenes.skinScene(for: theme) else { return nil }
            return "<section class=\"skin-scene\" data-skin-scene=\"\(theme.id)\"\(theme.id == first ? "" : " hidden")>\n\(scene)\n</section>"
        }.joined(separator: "\n")
        let links = themes.map { "<link rel=\"stylesheet\" href=\"../themes/\($0.id).css\">" }.joined(separator: "\n")
        let buttons = themes.map { theme in
            "<button type=\"button\" class=\"switch__option\" data-theme=\"\(theme.id)\" aria-pressed=\"false\">\(escape(ThemeIdentity.displayText(theme.name)))</button>"
        }.joined(separator: "\n      ")
        return """
        <!doctype html>
        <html lang="en">
        <head>
        <meta charset="utf-8">
        <meta name="viewport" content="width=device-width, initial-scale=1">
        <title>Skins gallery</title>
        <!-- Generated by design-tokens. Do not edit. DesignTokens \(DesignTokens.version) -->
        <link rel="stylesheet" href="gallery.css">
        <link rel="stylesheet" href="../components.css">
        \(links)
        </head>
        <body>
        <header class="frame">
          <h1 class="frame__title">Skins gallery</h1>
          <nav class="switch" aria-label="Theme">
              \(buttons)
          </nav>
        </header>
        <main>
          <div class="stage" data-theme-name="\(first)">
        \(GalleryScenes.sharedScene)
        \(skinScenes)
          </div>
        </main>
        <script src="gallery.js"></script>
        </body>
        </html>

        """
    }

    // MARK: The script and the page's own stylesheet

    private static let script = """
        /* Generated by design-tokens. Do not edit. */
        (function () {
          'use strict';
          var stage = document.querySelector('.stage');
          var options = Array.prototype.slice.call(document.querySelectorAll('.switch__option'));
          function known(id) {
            return options.some(function (option) { return option.getAttribute('data-theme') === id; });
          }
          function select(id) {
            if (!known(id)) { id = options.length ? options[0].getAttribute('data-theme') : ''; }
            stage.setAttribute('data-theme-name', id);
            Array.prototype.forEach.call(document.querySelectorAll('[data-skin-scene]'), function (scene) {
              scene.hidden = scene.getAttribute('data-skin-scene') !== id;
            });
            options.forEach(function (option) {
              option.setAttribute('aria-pressed', option.getAttribute('data-theme') === id ? 'true' : 'false');
            });
            return id;
          }
          function fromHash() {
            var match = /(?:^|[#&])theme=([a-z0-9_+-]+)/.exec(location.hash);
            select(match ? match[1] : stage.getAttribute('data-theme-name'));
          }
          options.forEach(function (option) {
            option.addEventListener('click', function () {
              location.hash = 'theme=' + select(option.getAttribute('data-theme'));
            });
          });
          window.addEventListener('hashchange', fromHash);
          fromHash();
        })();

        """

    private static let stylesheet = """
        /* Generated by design-tokens. Do not edit. The gallery's own chrome: neutral, never themed. */
        :root { color-scheme: light dark; --g-ink: CanvasText; --g-paper: Canvas; --g-rule: GrayText; }
        * { box-sizing: border-box; }
        body { margin: 0; font: 14px/1.4 system-ui, sans-serif; color: var(--g-ink); background: var(--g-paper); }
        .frame { display: flex; flex-wrap: wrap; align-items: baseline; gap: 12px 24px; padding: 12px 16px; border-bottom: 1px solid var(--g-rule); }
        .frame__title { margin: 0; font-size: 16px; font-weight: 600; }
