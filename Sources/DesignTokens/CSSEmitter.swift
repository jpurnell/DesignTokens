/// Emits the tokens as CSS custom properties.
///
/// Light values go on `:root`. Dark values go under `prefers-color-scheme: dark` (unless the page forces
/// light with `data-theme="light"`) and under `data-theme="dark"`. A dark value that has not been
/// measured is left out, so the light value carries through.
///
/// The dark selectors honour both `data-theme` and Bootstrap's `data-bs-theme`, on the root or on any
/// element, so a single component (a terminal mock-up) can be pinned to the dark appearance. Each colour also gets a
/// `-rgb` triple, because Bootstrap builds link colours as `rgba(var(--bs-link-color-rgb), ...)`.
public enum CSSEmitter {
    /// The complete stylesheet, ending in a newline.
    public static func emit() -> String {
        var lines = ["/* Generated by design-tokens. Do not edit. System colours: snapshot of \(Snapshot.systemRelease). */"]
        lines.append(":root {")
        for token in ColorToken.allCases {
            lines.append("  --\(kebab(token.rawValue)): \(token.light.hex);")
            lines.append("  --\(kebab(token.rawValue))-rgb: \(triple(token.light));")
        }
        for (index, color) in Palette.series.enumerated() {
            lines.append("  --series-\(index + 1): \(color.hex);")
        }
        for rule in Rule.allCases {
            lines.append("  --rule-\(rule.name): \(rule.points)px;")
        }
        lines.append("  --gutter: \(Grid.gutter)px;")
        lines.append("  --space-unit: \(Grid.baseUnit)px;")
        lines.append("  --columns: \(Grid.columns);")
        lines.append("  --radius-container: \(Radius.container);")
        lines.append("  --radius-control: \(Radius.control)px;")
        lines.append("  --font-sans: \(FontStack.sans);")
        lines.append("  --font-mono: \(FontStack.mono);")
        lines.append("  --font-serif-new-york: \(FontStack.serifNewYork);")
        lines.append("  --font-serif-garamond: \(FontStack.serifGaramond);")
        for style in TypeStyle.allCases {
            lines.append("  --type-\(style.name)-size: \(style.size);")
            lines.append("  --type-\(style.name)-line: \(style.line);")
            lines.append("  --type-\(style.name)-weight: \(style.weight);")
            lines.append("  --type-\(style.name)-tracking: \(style.tracking);")
            lines.append("  --type-\(style.name)-transform: \(style.uppercase ? "uppercase" : "none");")
        }
        lines.append("}")
        let hcLight = increasedContrastDeclarations(dark: false)
        let hcDark = increasedContrastDeclarations(dark: true)
        // Order matters: the light contrast block comes before the dark blocks so that a dark scheme
        // (higher specificity, or later at equal specificity) wins over it, then the dark contrast
        // blocks come last so they win over the standard dark values.
        lines.append("@media (prefers-contrast: more) {")
        lines.append("  :root {")
        lines.append(contentsOf: hcLight.map { "  " + $0 })
        lines.append("  }")
        lines.append("}")
        let dark = darkDeclarations()
        lines.append("@media (prefers-color-scheme: dark) {")
        lines.append("  :root:not([data-theme=\"light\"]):not([data-bs-theme=\"light\"]) {")
        lines.append(contentsOf: dark.map { "  " + $0 })
        lines.append("  }")
        lines.append("}")
        lines.append("[data-theme=\"dark\"],")
        lines.append("[data-bs-theme=\"dark\"] {")
        lines.append(contentsOf: dark)
        lines.append("}")
        lines.append("@media (prefers-contrast: more) and (prefers-color-scheme: dark) {")
        lines.append("  :root:not([data-theme=\"light\"]):not([data-bs-theme=\"light\"]) {")
        lines.append(contentsOf: hcDark.map { "  " + $0 })
        lines.append("  }")
        lines.append("}")
        lines.append("@media (prefers-contrast: more) {")
        lines.append("  [data-theme=\"dark\"],")
        lines.append("  [data-bs-theme=\"dark\"] {")
        lines.append(contentsOf: hcDark.map { "  " + $0 })
        lines.append("  }")
        lines.append("}")
        return lines.joined(separator: "\n") + "\n"
    }

    private static func darkDeclarations() -> [String] {
        var out: [String] = []
        for token in ColorToken.allCases {
            guard let dark = token.dark else { continue }
            out.append("  --\(kebab(token.rawValue)): \(dark.hex);")
            out.append("  --\(kebab(token.rawValue))-rgb: \(triple(dark));")
        }
        for (index, color) in Palette.seriesDark.enumerated() {
            out.append("  --series-\(index + 1): \(color.hex);")
        }
        out.append("  color-scheme: dark;")
        return out
    }

    private static func increasedContrastDeclarations(dark: Bool) -> [String] {
        var out: [String] = []
        for token in ColorToken.allCases {
            guard let color = dark ? token.increasedContrastDark : token.increasedContrastLight else { continue }
            out.append("  --\(kebab(token.rawValue)): \(color.hex);")
            out.append("  --\(kebab(token.rawValue))-rgb: \(triple(color));")
        }
        let series = dark ? Palette.seriesIncreasedContrastDark : Palette.seriesIncreasedContrast
        for (index, color) in series.enumerated() {
            out.append("  --series-\(index + 1): \(color.hex);")
        }
        return out
    }

    private static func triple(_ color: RGB) -> String {
        "\(color.red), \(color.green), \(color.blue)"
    }

    private static func kebab(_ name: String) -> String {
        var out = ""
        for character in name {
            if character.isUppercase { out += "-" + character.lowercased() } else { out.append(character) }
        }
        return out
    }
}
