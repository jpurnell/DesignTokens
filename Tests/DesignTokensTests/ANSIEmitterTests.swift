import Foundation
import Testing
@testable import DesignTokens

@Suite("ANSI emitter")
struct ANSIEmitterTests {
    private struct Row {
        var role, kind, hex, truecolor, c256, c16, glyph, ascii, note: String
    }

    /// The rows of one `[slot]` block, parsed by whitespace.
    private static func rows(_ text: String, slot: String) -> [Row] {
        var inBlock = false
        var out: [Row] = []
        for line in text.split(omittingEmptySubsequences: false, whereSeparator: \.isNewline) {
            if line.hasPrefix("[") { inBlock = line == "[\(slot)]"; continue }
            guard inBlock, !line.hasPrefix("#"), !line.isEmpty, !line.hasPrefix("role") else { continue }
            let f = line.split(separator: " ", omittingEmptySubsequences: true).map(String.init)
            guard f.count == 9 else { Issue.record("not nine fields: \(line)"); continue }
            out.append(Row(role: f[0], kind: f[1], hex: f[2], truecolor: f[3], c256: f[4], c16: f[5], glyph: f[6], ascii: f[7], note: f[8]))
        }
        return out
    }

    @Test("the header says generated, with the theme id, version, snapshot and hash")
    func header() throws {
        let text = try ANSIEmitter.emit(Theme.swiss)
        let first = try #require(text.split(whereSeparator: \.isNewline).first)
        #expect(first.hasPrefix("# Generated by design-tokens. Do not edit. Theme: swiss (Swiss) | DesignTokens \(DesignTokens.version) | System colours: snapshot of \(Snapshot.systemRelease) | hash fnv1a64:"))
        #expect(first.hasSuffix(try ThemeCodec.fingerprint(of: Theme.swiss)))
        #expect(text.hasSuffix("\n"))
    }

    @Test("Swiss light: the accent row is exact in all three depths (#FF8D28; 208; 33)")
    func swissAccentRow() throws {
        let rows = Self.rows(try ANSIEmitter.emit(Theme.swiss), slot: "light")
        let accent = try #require(rows.first { $0.role == "accent" })
        #expect(accent.kind == "fg")
        #expect(accent.hex == "#FF8D28")
        #expect(accent.truecolor == "38;2;255;141;40")
        #expect(accent.c256 == "38;5;208")
        #expect(accent.c16 == "33")
        #expect(accent.glyph == "-" && accent.ascii == "-" && accent.note == "-")
    }

    @Test("Swiss dark: the accent is #FF9230 and the background rows are background escapes (48)")
    func swissDark() throws {
        let rows = Self.rows(try ANSIEmitter.emit(Theme.swiss), slot: "dark")
        let accent = try #require(rows.first { $0.role == "accent" })
        #expect(accent.hex == "#FF9230")
        #expect(accent.truecolor == "38;2;255;146;48")
        for name in ["background", "surface"] {
            let row = try #require(rows.first { $0.role == name })
            #expect(row.kind == "bg")
            #expect(row.truecolor.hasPrefix("48;2;"))
            #expect(row.c256.hasPrefix("48;5;"))
            let code = try #require(Int(row.c16))
            #expect((40...47).contains(code) || (100...107).contains(code))
        }
    }

    @Test("every slot of every theme lists the twelve roles in order, then the series, then the extras sorted")
    func rowOrderAndCount() throws {
        for theme in Theme.all {
            let text = try ANSIEmitter.emit(theme)
            for slot in ThemeSlot.slots(for: theme) {
                let rows = Self.rows(text, slot: slot.name)
                let expected = ColorRole.allCases.map(\.rawValue)
                    + theme.palette.series.indices.map { "series-\($0 + 1)" }
                    + theme.palette.extras.keys.sorted().map { "extra.\($0)" }
                #expect(rows.map(\.role) == expected, "\(theme.id) \(slot.name)")
            }
        }
    }

    @Test("only the slots the theme supports have a block")
    func blocks() throws {
        let princeton = try ANSIEmitter.emit(Theme.princeton)
        #expect(princeton.contains("[light]") && princeton.contains("[light-increased]"))
        #expect(!princeton.contains("[dark]") && !princeton.contains("[dark-increased]"))
        let legacy = try ANSIEmitter.emit(Theme.legacyDark)
        #expect(legacy.contains("[dark]") && !legacy.contains("[light]"))
    }

    @Test("status is never colour alone: positive, negative and warning carry a glyph and an ASCII fallback; nothing else does")
    func statusGlyphs() throws {
        for theme in Theme.all {
            let text = try ANSIEmitter.emit(theme)
            for slot in ThemeSlot.slots(for: theme) {
                for row in Self.rows(text, slot: slot.name) {
                    switch row.role {
                    case "positive": #expect(row.glyph == "✓" && row.ascii == "+", "\(theme.id)")
                    case "negative": #expect(row.glyph == "✗" && row.ascii == "x", "\(theme.id)")
                    case "warning": #expect(row.glyph == "!" && row.ascii == "!", "\(theme.id)")
                    default: #expect(row.glyph == "-" && row.ascii == "-", "\(theme.id) \(row.role)")
                    }
                }
            }
        }
    }

    @Test("series rows carry the series name; the Swiss series are the eight system colours in order")
    func seriesNames() throws {
        let rows = Self.rows(try ANSIEmitter.emit(Theme.swiss), slot: "light").filter { $0.role.hasPrefix("series-") }
        #expect(rows.map(\.note) == ["orange", "indigo", "green", "purple", "yellow", "blue", "red", "cyan"])
        #expect(rows.map(\.hex) == ["#FF8D28", "#6155F5", "#34C759", "#CB30E0", "#FFCC00", "#0088FF", "#FF383C", "#00C0E8"])
    }

    @Test("a translucent role is composited over the background, so no hex has an alpha")
    func noAlphaInOutput() throws {
        var theme = Theme.swiss
        theme.palette.background.light = ColorValue(RGB(rgb: 0xFFFFFF))
        theme.palette.accent.light = ColorValue(RGB(red: 200, green: 100, blue: 0), alpha: 128.0 / 255.0)
        let accent = try #require(Self.rows(try ANSIEmitter.emit(theme), slot: "light").first { $0.role == "accent" })
        #expect(accent.hex == "#E3B17F")
        #expect(accent.truecolor == "38;2;227;177;127")
    }

    @Test("every colour in the file is a value of the theme, composited where translucent")
    func everyHexIsAThemeValue() throws {
        for theme in Theme.all {
            let text = try ANSIEmitter.emit(theme)
            for slot in ThemeSlot.slots(for: theme) {
                var allowed = Set<String>()
                for role in ColorRole.allCases { allowed.insert(slot.rgb(theme.palette[role], in: theme).hex) }
                for entry in theme.palette.series { allowed.insert(slot.rgb(entry.color, in: theme).hex) }
                for adaptive in theme.palette.extras.values { allowed.insert(slot.rgb(adaptive, in: theme).hex) }
                for row in Self.rows(text, slot: slot.name) { #expect(allowed.contains(row.hex), "\(theme.id) \(row.role)") }
            }
        }
    }

    @Test("the truecolor column is the hex column in decimal, and the 256 and 16 columns are the quantisers' answers")
    func columnsAgreeWithHex() throws {
        for theme in Theme.all {
            let text = try ANSIEmitter.emit(theme)
            for slot in ThemeSlot.slots(for: theme) {
                for row in Self.rows(text, slot: slot.name) {
                    let rgb = try #require(RGB(hex: row.hex))
                    let lead = row.kind == "bg" ? "48" : "38"
                    #expect(row.truecolor == "\(lead);2;\(rgb.red);\(rgb.green);\(rgb.blue)", "\(theme.id) \(row.role)")
                    #expect(row.c256 == "\(lead);5;\(TerminalColour.xterm256(rgb))", "\(theme.id) \(row.role)")
                    #expect(row.c16 == "\(TerminalColour.sgr16(TerminalColour.xterm16(rgb), background: row.kind == "bg"))", "\(theme.id) \(row.role)")
                }
            }
        }
    }

    @Test("the mapping is documented in the file")
    func documented() throws {
        let text = try ANSIEmitter.emit(Theme.swiss)
        #expect(text.contains("# 256-colour: nearest of xterm indices 16 to 255"))
        #expect(text.contains("# 16-colour: nearest of xterm's default sixteen"))
        #expect(text.contains("# Status is never colour alone"))
    }

    @Test("emitting is deterministic")
    func deterministic() throws {
        #expect(try ANSIEmitter.emit(Theme.ft) == ANSIEmitter.emit(Theme.ft))
    }
}
