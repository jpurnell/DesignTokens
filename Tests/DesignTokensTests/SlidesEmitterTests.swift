/// Collects `name -> val` of the `<a:srgbClr>` under each colour element, and the typefaces of a font scheme.
private final class SchemeReader: NSObject, XMLParserDelegate {
    var stack: [String] = []
    var colours: [String: String] = [:]
    var schemeName = ""
    var fonts: [String: String] = [:]

    func parser(_ parser: XMLParser, didStartElement elementName: String, namespaceURI: String?,
                qualifiedName qName: String?, attributes attributeDict: [String: String] = [:]) {
        if elementName == "a:clrScheme" || elementName == "a:fontScheme" { schemeName = attributeDict["name"] ?? "" }
        if elementName == "a:srgbClr", let parent = stack.last, let val = attributeDict["val"] { colours[parent] = val }
        if elementName == "a:latin", let parent = stack.last, let face = attributeDict["typeface"] { fonts[parent] = face }
        stack.append(elementName)
    }

    func parser(_ parser: XMLParser, didEndElement elementName: String, namespaceURI: String?, qualifiedName qName: String?) {
        stack.removeLast()
    }
}

@Suite("Slides emitter")
struct SlidesEmitterTests {
    private static func read(_ xml: String) throws -> SchemeReader {
        let reader = SchemeReader()
        let parser = XMLParser(data: Data(xml.utf8))
        parser.delegate = reader
        #expect(parser.parse(), "not well-formed: \(parser.parserError.map { "\($0)" } ?? "")")
        return reader
    }

    /// The `role hex` rows of a `[slot]` block (the block ends at the next `[`).
    private static func block(_ text: String, slot: String) -> [[String]] {
        var inBlock = false
        var out: [[String]] = []
        for line in text.split(omittingEmptySubsequences: false, whereSeparator: \.isNewline) {
            if line.hasPrefix("[") { inBlock = line == "[\(slot)]"; continue }
            guard inBlock, !line.hasPrefix("#"), !line.isEmpty else { continue }
            out.append(line.split(separator: " ", omittingEmptySubsequences: true).map(String.init))
        }
        return out
    }

    // MARK: Fonts

    @Test("the font chains drop the CSS-only names and keep the owner's order: SF Pro, Helvetica Neue, Helvetica, Arial")
    func fontChains() {
        #expect(SlidesEmitter.fontChain(.sans) == ["SF Pro Text", "SF Pro", "Helvetica Neue", "Helvetica", "Arial"])
        #expect(SlidesEmitter.fontChain(.mono) == ["SF Mono", "Menlo", "Consolas"])
        #expect(SlidesEmitter.fontChain(.serifNewYork) == ["New York", "Iowan Old Style", "Georgia"])
        #expect(SlidesEmitter.fontChain(.serifGaramond) == ["EB Garamond", "Garamond", "Iowan Old Style", "Georgia"])
    }

    @Test("a named face comes first, then its fallback's chain, without repeats")
    func namedChain() {
        #expect(SlidesEmitter.fontChain(.named("Avenir Next", fallback: .sans))
                == ["Avenir Next", "SF Pro Text", "SF Pro", "Helvetica Neue", "Helvetica", "Arial"])
        #expect(SlidesEmitter.fontChain(.named("Helvetica", fallback: .sans))
                == ["Helvetica", "SF Pro Text", "SF Pro", "Helvetica Neue", "Arial"])
    }

    // MARK: List

    @Test("the list has the header, a block per slot with every role, series and extra, and all fifteen type roles")
    func listContents() throws {
        for theme in Theme.all {
            let text = try SlidesEmitter.emitList(theme)
            let first = try #require(text.split(whereSeparator: \.isNewline).first)
            #expect(first.hasPrefix("# Generated by design-tokens. Do not edit. Theme: \(theme.id) (\(theme.name)) | DesignTokens \(DesignTokens.version) | System colours: snapshot of \(Snapshot.systemRelease) | hash fnv1a64:"), "\(theme.id)")
            for slot in ThemeSlot.slots(for: theme) {
                #expect(text.contains("[\(slot.name)]"), "\(theme.id)")
                let block = Self.block(text, slot: slot.name)
                var expected: [[String]] = ColorRole.allCases.map { [$0.rawValue, slot.rgb(theme.palette[$0], in: theme).hex] }
                expected += theme.palette.series.indices.map { ["series-\($0 + 1)", slot.rgb(theme.palette.series[$0].color, in: theme).hex] + theme.palette.series[$0].name.split(separator: " ").map(String.init) }
                expected += theme.palette.extras.keys.sorted().map { ["extra.\($0)", slot.rgb(theme.palette.extras[$0] ?? theme.palette.ink, in: theme).hex] }
                #expect(block == expected, "\(theme.id) \(slot.name)")
            }
            for role in TypeRole.allCases { #expect(text.contains("\n\(role.rawValue) "), "\(theme.id) type \(role)") }
            #expect(text.hasSuffix("\n"))
        }
    }

    @Test("Swiss: the list's colour rows are `role  hex`, and the label type row names the SF chain and the weight")
    func swissListRows() throws {
        let text = try SlidesEmitter.emitList(Theme.swiss)
        let light = try #require(text.range(of: "[light]\n"))
        let lightText = String(text[light.upperBound...])
        let accent = try #require(lightText.split(whereSeparator: \.isNewline).first { $0.hasPrefix("accent ") })
        #expect(accent.split(separator: " ", omittingEmptySubsequences: true).map(String.init) == ["accent", "#FF8D28"])
        let body = try #require(text.split(whereSeparator: \.isNewline).first { $0.hasPrefix("body ") })
        let spec = Theme.swiss.structure.type[.body]
        #expect(body.contains("SF Pro Text, SF Pro, Helvetica Neue, Helvetica, Arial"))
        #expect(body.contains("\(CSSNumber.string(spec.size)) pt"))
        #expect(body.contains("(\(spec.weight))"))
    }

    @Test("weight names follow Apple's scale: 400 Regular, 500 Medium, 600 Semibold, 700 Bold")
    func weightNames() {
        #expect(SlidesEmitter.weightName(100) == "Ultralight")
        #expect(SlidesEmitter.weightName(200) == "Thin")
        #expect(SlidesEmitter.weightName(300) == "Light")
        #expect(SlidesEmitter.weightName(400) == "Regular")
        #expect(SlidesEmitter.weightName(500) == "Medium")
        #expect(SlidesEmitter.weightName(600) == "Semibold")
        #expect(SlidesEmitter.weightName(700) == "Bold")
        #expect(SlidesEmitter.weightName(800) == "Heavy")
        #expect(SlidesEmitter.weightName(900) == "Black")
        #expect(SlidesEmitter.weightName(450) == "Medium")  // rounds half up to the next hundred
    }

    // MARK: Colour scheme XML

    @Test("Swiss light: dk1 ink, lt1 background, dk2 secondary ink, lt2 surface, accent1 the accent, accent2 to 6 the next five series, links")
    func swissLightScheme() throws {
        let slot = ThemeSlot.slots(for: Theme.swiss)[0]
        let reader = try Self.read(try SlidesEmitter.emitColourScheme(Theme.swiss, slot: slot))
        let p = Theme.swiss.palette
        func hex(_ a: Adaptive) -> String { String(slot.rgb(a, in: Theme.swiss).hex.dropFirst()) }
        #expect(reader.colours["a:dk1"] == hex(p.ink))
        #expect(reader.colours["a:lt1"] == hex(p.background))
        #expect(reader.colours["a:dk2"] == hex(p.secondaryInk))
        #expect(reader.colours["a:lt2"] == hex(p.surface))
        #expect(reader.colours["a:accent1"] == "FF8D28")
        // series 1 (orange) equals the accent, so it is skipped: indigo, green, purple, yellow, blue
        #expect(["a:accent2", "a:accent3", "a:accent4", "a:accent5", "a:accent6"].map { reader.colours[$0] }
                == ["6155F5", "34C759", "CB30E0", "FFCC00", "0088FF"])
        #expect(reader.colours["a:hlink"] == hex(p.link))
        #expect(reader.colours["a:folHlink"] == hex(p.secondaryInk))
        #expect(reader.schemeName == "Swiss light")
        #expect(reader.colours.count == 12)
    }

    @Test("Swiss dark: dk1 and dk2 are the dark pair (background, surface), lt1 and lt2 the light pair (ink, secondary ink)")
    func swissDarkScheme() throws {
        let slot = ThemeSlot.slots(for: Theme.swiss)[2]
        let reader = try Self.read(try SlidesEmitter.emitColourScheme(Theme.swiss, slot: slot))
        let p = Theme.swiss.palette
        func hex(_ a: Adaptive) -> String { String(slot.rgb(a, in: Theme.swiss).hex.dropFirst()) }
        #expect(reader.colours["a:dk1"] == hex(p.background))
        #expect(reader.colours["a:dk2"] == hex(p.surface))
        #expect(reader.colours["a:lt1"] == hex(p.ink))
        #expect(reader.colours["a:lt2"] == hex(p.secondaryInk))
        #expect(reader.colours["a:accent1"] == "FF9230")
        #expect(reader.schemeName == "Swiss dark")
    }

    @Test("a theme with fewer than five series distinct from the accent pads with muted")
    func padding() throws {
        var theme = Theme.swiss
        theme.palette.series = Array(theme.palette.series.prefix(3))   // orange (= accent), indigo, green
        let slot = ThemeSlot.slots(for: theme)[0]
        let reader = try Self.read(try SlidesEmitter.emitColourScheme(theme, slot: slot))
        let muted = String(slot.rgb(theme.palette.muted, in: theme).hex.dropFirst())
        #expect(["a:accent2", "a:accent3", "a:accent4", "a:accent5", "a:accent6"].map { reader.colours[$0] }
                == ["6155F5", "34C759", muted, muted, muted])
    }

    @Test("every theme and slot gives well-formed XML with the twelve colours, header comment included")
    func allSchemesWellFormed() throws {
        for theme in Theme.all {
            for slot in ThemeSlot.slots(for: theme) {
                let xml = try SlidesEmitter.emitColourScheme(theme, slot: slot)
                let reader = try Self.read(xml)
                #expect(reader.colours.count == 12, "\(theme.id) \(slot.name)")
                #expect(xml.hasPrefix("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n<!-- Generated by design-tokens. Do not edit. Theme: \(theme.id)"), "\(theme.id)")
                #expect(xml.contains("xmlns:a=\"http://schemas.openxmlformats.org/drawingml/2006/main\""))
                #expect(xml.hasSuffix("\n"))
            }
        }
    }

    // MARK: Font scheme XML

    @Test("Swiss font scheme: major is the heading role's first face, minor the body role's; the chain is in a comment")
    func fontScheme() throws {
        let xml = try SlidesEmitter.emitFontScheme(Theme.swiss)
        let reader = try Self.read(xml)
        #expect(reader.fonts["a:majorFont"] == "SF Pro Text")
        #expect(reader.fonts["a:minorFont"] == "SF Pro Text")
        #expect(reader.schemeName == "Swiss")
        #expect(xml.contains("Fallbacks: SF Pro, Helvetica Neue, Helvetica, Arial"))
    }

    @Test("every theme's font scheme is well-formed and names a face for both fonts")
    func allFontSchemes() throws {
        for theme in Theme.all {
            let reader = try Self.read(try SlidesEmitter.emitFontScheme(theme))
            let major = try #require(reader.fonts["a:majorFont"])
            let minor = try #require(reader.fonts["a:minorFont"])
            #expect(!major.isEmpty && !minor.isEmpty, "\(theme.id)")
            #expect(SlidesEmitter.fontChain(theme.structure.type[.heading].family).first == major, "\(theme.id)")
            #expect(SlidesEmitter.fontChain(theme.structure.type[.body].family).first == minor, "\(theme.id)")
        }
    }

    @Test("XML text is escaped: a theme name with & and < stays well-formed")
    func escaping() throws {
        var theme = Theme.swiss
        theme.name = "R&D <Swiss> \"x\""
        let slot = ThemeSlot.slots(for: theme)[0]
        _ = try Self.read(try SlidesEmitter.emitColourScheme(theme, slot: slot))
        _ = try Self.read(try SlidesEmitter.emitFontScheme(theme))
        #expect(try SlidesEmitter.emitFontScheme(theme).contains("R&amp;D &lt;Swiss&gt; &quot;x&quot;"))
    }

    @Test("emitting is deterministic")
    func deterministic() throws {
        #expect(try SlidesEmitter.emitList(Theme.house) == SlidesEmitter.emitList(Theme.house))
    }
}
